// Run independently from the app target:
// swiftc -module-cache-path /tmp/aiglass-gen1-module-cache \
//   AIGlass/Bluetooth/Gen1/Gen1Protocol.swift Tests/Gen1ProtocolTests.swift \
//   -o /tmp/aiglass-gen1-tests && /tmp/aiglass-gen1-tests
@main
enum Gen1ProtocolTests {
    struct Failure: Error, CustomStringConvertible { let description: String }
    static var checks = 0

    static func check(_ condition: @autoclosure () -> Bool, _ name: String) throws {
        checks += 1
        guard condition() else { throw Failure(description: name) }
    }

    static func expectError(_ name: String, _ body: () throws -> Void) throws {
        do { try body() } catch is Gen1ProtocolError { checks += 1; return }
        throw Failure(description: name)
    }

    static func response(_ command: UInt8, _ payload: Data) throws -> Data {
        var packet = try Gen1ControlCodec.buildCommand(command: command, payload: payload)
        packet[1] = 3
        packet[2] = 2
        let crc = Gen1ControlCodec.crc16Modbus(packet.dropLast(2))
        packet[packet.count - 2] = UInt8(crc & 0xFF)
        packet[packet.count - 1] = UInt8(crc >> 8)
        return packet
    }

    static func voice(_ type: Gen1VoiceFrameType, _ sequence: Int, _ payload: Data = Data()) -> Data {
        var header = Data([0xA5, 2, type.rawValue, 0, UInt8(sequence >> 8), UInt8(sequence & 0xFF),
                           UInt8(payload.count & 0xFF), UInt8(payload.count >> 8)])
        let crc = Gen1ControlCodec.crc16Modbus(header + payload)
        header.append(contentsOf: [UInt8(crc & 0xFF), UInt8(crc >> 8)])
        return header + payload
    }

    static func voiceFrame(_ type: Gen1VoiceFrameType, _ sequence: Int, _ bytes: [UInt8] = []) -> Gen1VoiceFrame {
        Gen1VoiceFrame(type: type, flags: 0, sequence: sequence, payload: Data(bytes))
    }

    static func imageEnd(_ jpeg: Data, status: UInt8 = 0) -> Data {
        let crc = Gen1ControlCodec.crc16Modbus(jpeg)
        return Data([3, status, UInt8(crc >> 8), UInt8(crc & 0xFF),
                     UInt8((jpeg.count >> 24) & 0xFF), UInt8((jpeg.count >> 16) & 0xFF),
                     UInt8((jpeg.count >> 8) & 0xFF), UInt8(jpeg.count & 0xFF)])
    }

    static func main() throws {
        try controlTests()
        try voiceTests()
        try routingTests()
        try imageTests()
        try metadataTests()
        #if canImport(AVFoundation)
        try nativeWAVReadTest()
        #endif
        print("Gen1 protocol: \(checks) assertions passed")
    }

    static func controlTests() throws {
        // These are independent Android reference vectors, not values generated by this codec.
        let vectors: [(UInt8, Data, [UInt8])] = [
            (Gen1Commands.battery, Data(), [0xAA, 2, 3, 5, 0, 0, 0x71, 0x94]),
            (Gen1Commands.translateRecord, Data([1]), [0xAA, 2, 3, 0x90, 0, 1, 1, 0xB9, 0xB8]),
            (Gen1Commands.translateRecord, Data([0]), [0xAA, 2, 3, 0x90, 0, 1, 0, 0x78, 0x78]),
            (Gen1Commands.aiVoice, Data([1]), [0xAA, 2, 3, 1, 0, 1, 1, 0x95, 0x44]),
            (Gen1Commands.aiVoice, Data([0]), [0xAA, 2, 3, 1, 0, 1, 0, 0x54, 0x84]),
            (Gen1Commands.aiImage, Data(), [0xAA, 2, 3, 0x70, 0, 0, 0x60, 0x4E])
        ]
        for (command, payload, bytes) in vectors {
            let encoded = try Gen1ControlCodec.buildCommand(command: command, payload: payload)
            try check(encoded == Data(bytes), "Android command vector \(command)")
        }
        try check(Gen1ControlCodec.crc16Modbus(Data("123456789".utf8)) == 0x4B37, "standard Modbus CRC vector")
        let first = try response(Gen1Commands.battery, Data([88, 1]))
        let second = try response(Gen1Commands.deviceStatusChanged, Data([2]))
        for cut in 0...first.count {
            let decoder = Gen1ControlStreamDecoder()
            let result = decoder.append(first.prefix(cut)) + decoder.append(first.dropFirst(cut) + second)
            try check(result.count == 2 && result[0].payload == Data([88, 1]) && result[1].command == Gen1Commands.deviceStatusChanged,
                      "control split at \(cut)")
        }
        var bad = first
        bad[bad.count - 1] ^= 0xFF
        let recovered = Gen1ControlStreamDecoder().append(Data([1, 2, 3]) + bad + first)
        try check(recovered.count == 1 && recovered[0].payload == Data([88, 1]), "control CRC resynchronization")
        let oversizedHeader = Data([0xAA, 3, 2, 5, 0xFF, 0xFF])
        try check(Gen1ControlStreamDecoder().append(oversizedHeader + first).count == 1, "oversized control header recovery")
        let maximum = Data((0..<Gen1ControlCodec.maxPayloadSize).map { UInt8($0 & 0xFF) })
        let maximumPacket = try Gen1ControlCodec.buildCommand(command: Gen1Commands.aiImage, payload: maximum)
        try check(Gen1ControlCodec.parse(maximumPacket)?.payload == maximum, "maximum control payload")
        try expectError("reject oversized outgoing control payload") {
            _ = try Gen1ControlCodec.buildCommand(command: Gen1Commands.aiImage, payload: maximum + Data([0]))
        }
        let busy = try response(Gen1Commands.takePhoto, Data([0xE3]))
        try check(Gen1ControlCodec.parse(busy)?.isBusy == true, "busy response")
        try check(Gen1ControlCodec.parse(first.dropLast()) == nil, "truncated control CRC")
        try check(Gen1ControlCodec.parse(first + Data([0])) == nil, "control trailing bytes rejected")
        var prefixed = Data([0xFF, 0xFF]) + first
        prefixed.removeFirst(2)
        try check(prefixed.startIndex > 0 && Gen1ControlCodec.parse(prefixed)?.payload == Data([88, 1]), "nonzero Data indices")
        let decoder = Gen1ControlStreamDecoder()
        _ = decoder.append(first.prefix(4))
        decoder.reset()
        try check(decoder.append(second).count == 1, "control reset drops prior fragments")
        try check(Gen1ControlStreamDecoder().append(Data(repeating: 0, count: 100_000) + first).count == 1,
                  "large corrupt control stream recovers")
    }

    static func voiceTests() throws {
        let start = voice(.start, 0)
        let data = voice(.data, 1, Data([10, 20, 30]))
        let end = voice(.end, 2)
        let frames = Gen1VoiceStreamDecoder().append(start + data + end)
        try check(frames.map(\.type) == [.start, .data, .end] && frames[1].payload == Data([10, 20, 30]), "voice CRC preceding payload")
        let longPayload = Data((0..<40).map(UInt8.init))
        let packet = voice(.data, 7, longPayload)
        for cut in 0...packet.count {
            let decoder = Gen1VoiceStreamDecoder()
            let decoded = decoder.append(packet.prefix(cut)) + decoder.append(packet.dropFirst(cut))
            try check(decoded.count == 1 && decoded[0].sequence == 7 && decoded[0].payload == longPayload, "voice split at \(cut)")
        }
        let decoder = Gen1VoiceStreamDecoder()
        try check(decoder.append(packet.prefix(20)).isEmpty && decoder.append(packet[20..<40]).isEmpty, "ATT fragmentation buffers")
        try check(decoder.append(packet.dropFirst(40)).first?.payload == longPayload, "ATT fragment completion")
        var bad = data
        bad[8] ^= 0xFF
        if case .dropped(let drop) = decoder.parseNotification(bad) {
            try check(drop.reason == "CRC mismatch" && drop.sequence == 1, "voice CRC diagnostics")
        } else { throw Failure(description: "bad voice CRC accepted") }
        try check(decoder.append(bad + data).count == 1, "bad voice CRC affects one frame")
        try check(decoder.append(voice(.data, 2)).isEmpty, "empty DATA rejected")
        try check(decoder.append(Data([0xA5, 2, 1, 0, 0, 0, 0xFF, 0xFF, 0, 0]) + data).count == 1, "oversized voice length recovers")
        try check(Gen1VoiceStreamDecoder().append(Data(repeating: 0, count: 100_000) + start).count == 1, "large corrupt voice stream recovers")
        // A corrupted length swallowing another frame must not discard the valid nested frame.
        var swallowed = voice(.data, 3, Data(repeating: 0, count: data.count))
        swallowed.replaceSubrange(10..<swallowed.count, with: data)
        try check(Gen1VoiceStreamDecoder().append(swallowed).first?.sequence == 1, "voice resync within CRC-rejected frame")
        let maximum = Data(repeating: 3, count: Gen1VoiceStreamDecoder.maxPayloadSize)
        try check(decoder.append(voice(.data, 4, maximum)).first?.payload == maximum, "maximum voice payload")
        let tracker = Gen1VoiceSequenceTracker()
        try check(tracker.onFrame(voiceFrame(.start, 0)) == .accepted, "sequence START")
        try check(tracker.onFrame(voiceFrame(.data, 1, [1])) == .accepted, "sequence first DATA")
        try check(tracker.onFrame(voiceFrame(.data, 1, [1])) == .duplicateOrLate(expected: 2, actual: 1), "duplicate suppressed")
        try check(tracker.onFrame(voiceFrame(.data, 3, [1])) == .gap(expected: 2, actual: 3, missing: 1), "sequence gap reported")
        try check(tracker.onFrame(voiceFrame(.data, 4, [1])) == .accepted, "sequence continues after gap")
        _ = tracker.onFrame(voiceFrame(.start, 0xFFFF))
        try check(tracker.onFrame(voiceFrame(.data, 0, [1])) == .accepted, "sequence UInt16 wrap")
        _ = tracker.onFrame(voiceFrame(.end, 1))
        try check(tracker.onFrame(voiceFrame(.data, 20, [1])) == .accepted, "END resets sequence")
        tracker.reset()
        try check(tracker.onFrame(voiceFrame(.data, 10, [1])) == .accepted, "explicit sequence reset")
        _ = decoder.append(packet.prefix(4))
        decoder.reset()
        try check(decoder.append(start).count == 1, "voice reset clears fragment")
    }

    static func routingTests() throws {
        let router = Gen1TranslationAudioRouter()
        let start = voiceFrame(.start, 0)
        let data = voiceFrame(.data, 1, [1, 2])
        let end = voiceFrame(.end, 2)
        try check(router.onFrame(start) == .ai(start), "unrequested stream belongs to AI")
        router.onStartRequested()
        try check(router.onFrame(data) == .ai(data), "pending translation leaves prior AI DATA alone")
        try check(router.onFrame(end) == .ignore, "prior END does not end pending translation")
        try check(router.onAck(1) == .ignore, "positive ACK awaits START")
        let wrongStart = voiceFrame(.start, 9)
        try check(router.onFrame(wrongStart) == .ai(wrongStart), "nonzero START is not translation")
        try check(router.onFrame(start) == .translationStarted, "translation starts on sequence zero")
        try check(router.onFrame(data) == .translationData(sequence: 1, opus: Data([1, 2])), "translation routes Opus")
        router.onStopRequested()
        try check(router.onAck(0) == .ignore, "stop ACK preserves audio boundary")
        try check(router.onFrame(data) == .translationData(sequence: 1, opus: Data([1, 2])), "pending stop keeps final DATA")
        try check(router.onFrame(end) == .translationStopped, "END completes translation")
        try check(router.onFrame(data) == .ai(data), "next DATA returns to AI")
        router.onStartRequested()
        try check(router.onAck(0) == .translationStartFailed, "zero ACK fails pending start")
        try check(router.onAck(0) == .ignore, "duplicate zero ACK ignored")
        router.onStartRequested()
        router.onStartFailed()
        try check(router.onFrame(start) == .ai(start), "local write failure resets pending start")
        router.onStartRequested()
        _ = router.onFrame(start)
        router.reset()
        try check(router.onFrame(data) == .ai(data), "disconnect resets router")
        router.onStartRequested()
        _ = router.onFrame(start)
        router.onStopRequested()
        router.discardPendingStream()
        try check(router.onFrame(data) == .ignore, "abandoned translation tail is not AI")
        try check(router.onFrame(start) == .ai(start), "fresh AI START recovers after missing translation END")
        try check(router.onFrame(data) == .ai(data), "recovered AI DATA no longer routes into translation")
        router.onStartRequested()
        router.discardPendingStream()
        try check(router.onFrame(end) == .ignore, "discarded translation END is not AI END")
        try check(router.onFrame(data) == .ai(data), "discarded END restores idle route")
    }

    static func imageTests() throws {
        let jpeg = Data([0xFF, 0xD8, 1, 2, 3, 4, 0xFF, 0xD9])
        let first = Data([2, 0, 0]) + jpeg.prefix(4)
        let second = Data([2, 0, 1]) + jpeg.suffix(4)
        let start = Data([1, 0, 0, 2])
        let assembler = Gen1ImageAssembler()
        try check(assembler.append(start) == .started(expectedChunks: 2), "image START")
        _ = assembler.append(second)
        _ = assembler.append(second)
        try check(assembler.append(first) == .progress(receivedChunks: 2, expectedChunks: 2, receivedBytes: 8, shouldSendAck: true, nextExpectedSequence: 2),
                  "out-of-order image and duplicate chunks")
        try check(assembler.append(imageEnd(jpeg)) == .completed(jpeg: jpeg), "image CRC and markers verified")
        _ = assembler.append(start)
        _ = assembler.append(second)
        try check(assembler.append(imageEnd(jpeg, status: 1)) == .needRetransmit(missingSequences: [0], round: 1, expectedChunks: 2, receivedChunks: 1, receivedBytes: 4),
                  "failure END still requests missing image chunks")
        try check(assembler.append(first) == .completed(jpeg: jpeg), "DATA-only retransmission completes failure END")
        _ = assembler.append(start)
        _ = assembler.append(second)
        _ = assembler.append(imageEnd(jpeg))
        for _ in 0..<4 {
            try check(assembler.append(imageEnd(jpeg)) == .progress(receivedChunks: 1, expectedChunks: 2,
                        receivedBytes: 4, shouldSendAck: false, nextExpectedSequence: 0), "duplicate END preserves retransmission budget")
        }
        try check(assembler.requestRetransmission() == .needRetransmit(missingSequences: [0], round: 2, expectedChunks: 2, receivedChunks: 1, receivedBytes: 4), "image retry round two")
        _ = assembler.requestRetransmission()
        try check(assembler.requestRetransmission() == .error(reason: "image chunks still missing after 3 retransmit rounds"), "bounded image retransmission")
        try check(assembler.requestRetransmission() == nil, "failed transfer resets state")
        _ = assembler.append(start)
        _ = assembler.append(second)
        _ = assembler.append(imageEnd(jpeg))
        var conflictingEnd = imageEnd(jpeg)
        conflictingEnd[7] = 9
        try check(assembler.append(conflictingEnd) == .error(reason: "image END metadata changed"), "conflicting END metadata rejected")
        _ = assembler.append(Data([1, 0, 0, 17]))
        for sequence in 0..<17 {
            let event = assembler.append(Data([2, 0, UInt8(sequence), 1]))
            try check(event == .progress(receivedChunks: sequence + 1, expectedChunks: 17, receivedBytes: sequence + 1,
                                         shouldSendAck: sequence >= 15, nextExpectedSequence: sequence + 1), "image window ACK \(sequence)")
        }
        _ = assembler.append(start)
        _ = assembler.append(first)
        _ = assembler.append(second)
        var invalidCRC = imageEnd(jpeg)
        invalidCRC[2] ^= 0xFF
        try check(assembler.append(invalidCRC) == .error(reason: "image CRC mismatch"), "bad image CRC rejected")
        _ = assembler.append(start)
        _ = assembler.append(first)
        _ = assembler.append(second)
        var wrongLength = imageEnd(jpeg)
        wrongLength[7] = 9
        try check(assembler.append(wrongLength) == .error(reason: "image length mismatch: expected=9 actual=8"), "bad image length rejected")
        _ = assembler.append(Data([1, 0, 0, 1]))
        let notJPEG = Data([1, 2, 3, 4])
        _ = assembler.append(Data([2, 0, 0]) + notJPEG)
        try check(assembler.append(imageEnd(notJPEG)) == .error(reason: "invalid JPEG markers"), "JPEG markers checked")
        try check(assembler.append(first) == .error(reason: "image DATA received before START"), "image DATA needs START")
        try check(assembler.append(Data([1, 0, 0, 0])) == .error(reason: "invalid image chunk count"), "zero image chunks rejected")
        _ = assembler.append(Data([1, 0, 0, 1]))
        try check(assembler.append(Data([2, 0, 1, 1])) == .error(reason: "image sequence out of range: seq=1 chunks=1"), "image sequence bound")
        _ = assembler.append(start)
        try check(assembler.append(Data([3, 0, 0, 0, 1, 0, 0, 0])) == .error(reason: "image is too large"), "oversized image metadata")
        _ = assembler.append(Data([1, 0, 0, 1]))
        let tooLarge = Data([2, 0, 0]) + Data(repeating: 1, count: Gen1ImageAssembler.maxJPEGSize + 1)
        try check(assembler.append(tooLarge) == .error(reason: "image is too large"), "bounded image assembly memory")
    }

    static func metadataTests() throws {
        try check(Gen1Payloads.fileListQuery() == Data([0, 0]), "two-byte file-list query")
        try check(Gen1Payloads.syncTime(epochSeconds: 1) == Data("0000000001".utf8), "decimal ten-byte timestamp")
        try check(Gen1Payloads.firmwareURL("https://example.test/fw.bin") == Data([1]) + Data("https://example.test/fw.bin".utf8), "firmware URL prefix")
        try check(Gen1Payloads.oneByte(-1) == Data([0]) && Gen1Payloads.oneByte(1000) == Data([255]), "one-byte clamping")
        let ack = try Gen1Payloads.imageChunkAck(16)
        try check(ack == Data([5, 0, 16]), "image ACK reference vector")
        let retransmit = try Gen1Payloads.imageRetransmitRequest([3, 0x102])
        try check(retransmit == Data([4, 2, 0, 3, 1, 2]), "image retransmit reference vector")
        try expectError("invalid image ACK rejected") { _ = try Gen1Payloads.imageChunkAck(65536) }
        try expectError("empty retransmit rejected") { _ = try Gen1Payloads.imageRetransmitRequest([]) }
        try expectError("more than eight retransmits rejected") { _ = try Gen1Payloads.imageRetransmitRequest(Array(0..<9)) }
        try expectError("negative retransmit sequence rejected") { _ = try Gen1Payloads.imageRetransmitRequest([-1]) }
        for (profile, seconds) in DeviceCapabilities.allRecordDurationSeconds.enumerated() {
            let duration = try Gen1Payloads.recordDuration(seconds: seconds)
            try check(duration == Data([UInt8(profile)]), "record duration profile \(profile)")
        }
        try expectError("unknown record duration rejected") { _ = try Gen1Payloads.recordDuration(seconds: 30) }
        let files = Data("20260101_120000.jpg,clip.mp4,clip_thumb.jpg,notes.txt,../x.jpg,a/b.jpg,a\\b.jpg,preview.jpg,normal.PNG\0\r\n".utf8)
        try check(Gen1FileListParser.parseMediaFiles(files) == ["20260101_120000.jpg", "clip.mp4", "normal.PNG"], "file list safety and thumbnail exclusion")
        let storage = Data([0, 5]) + Data("29.3G".utf8) + Data([4]) + Data("3.7M".utf8)
        try check(Gen1StorageParser.parse(storage) == "29.3G / 3.7M", "documented storage response")
        try check(Gen1StorageParser.parse(storage.dropLast()) == nil, "truncated storage response")
        try check(Gen1StorageParser.parse(storage + Data([0])) == nil, "storage trailing bytes rejected")
        try check(Gen1StorageParser.parse(Data([0, 1, 0x20, 1, 0x30])) == nil, "blank storage rejected")
        try check(Gen1StorageParser.parse(Data([0, 1, 0xFF, 1, 0x30])) == nil, "non-ASCII storage rejected")
        try check(Gen1DeviceStatusMapper.toDomainStatus(0) == .standby && Gen1DeviceStatusMapper.toDomainStatus(1) == .videoRecording
                  && Gen1DeviceStatusMapper.toDomainStatus(2) == .networkOperating && Gen1DeviceStatusMapper.toDomainStatus(3) == .photoTaking
                  && Gen1DeviceStatusMapper.toDomainStatus(4) == .shuttingDown && Gen1DeviceStatusMapper.toDomainStatus(99) == .unknown,
                  "all documented runtime status mappings")
        try check(DeviceGeneration.fromDeviceName("  L1 Glass ") == .gen1G5K61 && DeviceGeneration.fromDeviceName("moco g5k61") == .gen1G5K61
                  && DeviceGeneration.fromDeviceName("Astra A1") == .unknown && DeviceGeneration.fromDeviceName(nil) == .unknown, "generation name hints")
        try check(DeviceCapabilities.gen1.aiVoice && DeviceCapabilities.gen1.aiRecording && DeviceCapabilities.gen1.translation
                  && DeviceCapabilities.gen1.aiImageRecognition && DeviceCapabilities.gen1.bluetoothUpgrade && !DeviceCapabilities.gen1.videoResolution
                  && !DeviceCapabilities.gen1.voiceWakeupSetting, "Gen1 verified capabilities")
        try check(DeviceCapabilities.gen2.videoResolution && DeviceCapabilities.gen2.voiceWakeupSetting && !DeviceCapabilities.unknown.photo, "Gen2 and unknown capabilities")
        try check(Gen1Commands.aiRecord == 0x37 && Gen1Commands.masterReset == 0x74 && Gen1Commands.firmwareOTAProgress == 0x3A, "documented command aliases and OTA progress")
        let wav = Gen1PCM.wavHeader(pcmBytes: 32_000)
        let expectedWAV: [UInt8] = [
            0x52, 0x49, 0x46, 0x46, 0x24, 0x7D, 0, 0, 0x57, 0x41, 0x56, 0x45,
            0x66, 0x6D, 0x74, 0x20, 16, 0, 0, 0, 1, 0, 1, 0,
            0x80, 0x3E, 0, 0, 0, 0x7D, 0, 0, 2, 0, 16, 0,
            0x64, 0x61, 0x74, 0x61, 0, 0x7D, 0, 0
        ]
        try check(wav == Data(expectedWAV), "one-second PCM16000mono16 WAV reference header")
    }

    #if canImport(AVFoundation)
    static func nativeWAVReadTest() throws {
        let url = FileManager.default.temporaryDirectory.appendingPathComponent("gen1-wav-test-\(UUID().uuidString).wav")
        defer { try? FileManager.default.removeItem(at: url) }
        let pcm = Data(repeating: 0, count: 32_000)
        try (Gen1PCM.wavHeader(pcmBytes: UInt32(pcm.count)) + pcm).write(to: url)
        let audio = try AVAudioFile(forReading: url)
        try check(audio.length == 16_000 && audio.processingFormat.sampleRate == 16_000
                  && audio.processingFormat.channelCount == 1, "AVAudioFile recognizes PCM WAV format and duration")
        guard let buffer = AVAudioPCMBuffer(pcmFormat: audio.processingFormat, frameCapacity: 16_000) else {
            throw Failure(description: "AVAudioPCMBuffer allocation")
        }
        try audio.read(into: buffer)
        try check(buffer.frameLength == 16_000, "native audio reader decodes complete recording")
    }
    #endif
