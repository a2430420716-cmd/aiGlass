import Foundation

@main
struct TranslationAudioSessionTests {
    static func main() {
        var assertions = 0
        func check(_ condition: @autoclosure () -> Bool, _ message: String) {
            assertions += 1
            precondition(condition(), message)
        }

        var pcm = TranslationPCMStatistics()
        check(pcm.rms == 0 && pcm.durationMs == 0, "Empty PCM has finite diagnostics")
        pcm.append(Data([0, 0, 0, 0x80, 0xFF, 0x7F]))
        check(pcm.samples == 3 && pcm.bytes == 6, "Count PCM16 samples")
        check(pcm.peak == 32_768, "Negative full scale must not overflow Int16")
        check(abs(pcm.rms - sqrt((Double(32_768) * 32_768 + Double(32_767) * 32_767) / 3)) < 0.001,
              "Read signed little-endian audio when computing energy")
        var silence = TranslationPCMStatistics()
        silence.append(Data(repeating: 0, count: 32_000))
        check(silence.durationMs == 1_000 && silence.peak == 0 && silence.rms == 0,
              "One second of silence remains distinguishable from missing audio")

        var attempt = TranslationConnectionAttempt()
        check(!attempt.isCurrent(0), "No callback is current before connect")
        let first = attempt.begin()
        check(attempt.isCurrent(first), "First URL lookup belongs to current connection")
        attempt.cancel()
        check(!attempt.isCurrent(first), "Closing suppresses cancelled socket errors")
        check(!attempt.isCurrent(attempt.current), "Closed session cannot deliver callbacks")
        let second = attempt.begin()
        check(!attempt.isCurrent(first), "Old URL response cannot open a replacement socket")
        check(attempt.isCurrent(second), "New session remains current after stale callback")
        let third = attempt.begin()
        check(!attempt.isCurrent(second), "Reconnect invalidates previous receive loop")
        check(attempt.isCurrent(third), "Latest receive loop is accepted")

        let now = Date(timeIntervalSince1970: 1_000)
        var gate = TranslationAudioInputState()
        gate.serviceReady()
        check(!gate.canSendAudio(opened: true, ready: true), "Ready alone cannot start the mic")
        check(!gate.start(opened: false, ready: true, now: now), "Closed socket rejects start")
        check(!gate.recording, "Failed start must not save recording intent")
        check(!gate.start(opened: true, ready: false, now: now), "Unready socket rejects start")
        check(gate.start(opened: true, ready: true, now: now), "Device START opens input")
        check(gate.canSendAudio(opened: true, ready: true), "PCM can flow after START")
        gate.serviceReady()
        check(gate.canSendAudio(opened: true, ready: true), "Duplicate ready must not mute ongoing recording")
        check(gate.start(opened: true, ready: true, now: now), "Duplicate start is idempotent")
        gate.beginBackendProcessing()
        check(!gate.canSendAudio(opened: true, ready: true), "Backend busy temporarily gates PCM")
        gate.serviceReady()
        check(gate.canSendAudio(opened: true, ready: true), "Ready resumes recording after backend busy")
        gate.beginBackendProcessing()
        gate.backendTurnFinished()
        check(gate.canSendAudio(opened: true, ready: true), "Turn final resumes existing recording")
        gate.stop(now: now)
        check(!gate.canSendAudio(opened: true, ready: true), "Local stop closes input")
        gate.serviceReady()
        gate.backendTurnFinished()
        check(!gate.canSendAudio(opened: true, ready: true), "Late ready/final cannot reopen a stopped mic")
        check(!gate.start(opened: true, ready: true, now: now.addingTimeInterval(0.1)), "Rapid restart remains debounced")
        check(gate.start(opened: true, ready: true, now: now.addingTimeInterval(0.5)), "Intentional later start succeeds")
        check(!gate.canSendAudio(opened: false, ready: true), "Disconnect suppresses PCM")
        check(!gate.canSendAudio(opened: true, ready: false), "Unready socket suppresses PCM")
        gate.close()
        check(!gate.recording, "Close removes old recording intent")
        check(gate.start(opened: true, ready: true, now: now), "New socket has no old stop debounce")

        let firstPlayback = gate.playbackScheduled(duration: 1, now: now)
        let secondPlayback = gate.playbackScheduled(duration: 1, now: now)
        check(!gate.canSendAudio(opened: true, ready: true, now: now), "Playing translation blocks echo uploads")
        gate.serviceReady()
        gate.backendTurnFinished()
        check(!gate.canSendAudio(opened: true, ready: true, now: now), "Ready and VAD cannot override playback suppression")
        gate.playbackCompleted(firstPlayback, now: now)
        check(!gate.canSendAudio(opened: true, ready: true, now: now.addingTimeInterval(1)), "Queued speech remains protected until all buffers play")
        gate.playbackCompleted(secondPlayback, now: now.addingTimeInterval(1))
        check(!gate.canSendAudio(opened: true, ready: true, now: now.addingTimeInterval(1.49)), "Keep 500ms echo tail after actual output completion")
        check(gate.canSendAudio(opened: true, ready: true, now: now.addingTimeInterval(1.5)), "Resume uploads without restarting recording")
        gate.stop(now: now.addingTimeInterval(2))
        gate.backendTurnFinished()
        check(!gate.canSendAudio(opened: true, ready: true, now: now.addingTimeInterval(3)), "Late VAD cannot reopen a manually stopped mic")
        gate.close()
        check(gate.start(opened: true, ready: true, now: now), "Next session starts independently")
        let cancelledPlayback = gate.playbackScheduled(duration: 1, now: now)
        gate.playbackCancelled(now: now)
        check(gate.canSendAudio(opened: true, ready: true, now: now.addingTimeInterval(0.5)), "Cancelled playback cannot leave the mic blocked")

        let replacementPlayback = gate.playbackScheduled(duration: 2, now: now.addingTimeInterval(1))
        gate.playbackCompleted(cancelledPlayback, now: now.addingTimeInterval(1))
        check(!gate.canSendAudio(opened: true, ready: true, now: now.addingTimeInterval(1)),
              "Late completion of cancelled output cannot release replacement playback")
        check(!gate.hasExpiredPlayback(now: now.addingTimeInterval(5.9)), "Allow output duration plus callback grace")
        check(gate.hasExpiredPlayback(now: now.addingTimeInterval(6)), "Missing playback callback reaches bounded recovery deadline")
        gate.playbackCancelled(now: now.addingTimeInterval(6))
        check(gate.canSendAudio(opened: true, ready: true, now: now.addingTimeInterval(6.5)),
              "Stopping stuck playback releases input after echo tail")
        gate.close()
        check(gate.start(opened: true, ready: true, now: now), "Recording starts after close")
        let freshPlayback = gate.playbackScheduled(duration: 1, now: now)
        gate.playbackCompleted(replacementPlayback, now: now)
        check(!gate.canSendAudio(opened: true, ready: true, now: now), "Old session completion cannot release new session playback")
        gate.playbackCompleted(freshPlayback, now: now)
        gate.close()
        check(gate.start(opened: true, ready: true, now: now), "Start phone input")
        check(!TranslationAudioInputState.shouldSuppressPlayback(phoneMicrophone: true, bluetoothOutput: true),
              "Phone mic plus glasses output permits continuous speech")
        check(TranslationAudioInputState.shouldSuppressPlayback(phoneMicrophone: true, bluetoothOutput: false),
              "Phone speaker still requires echo suppression")
        check(TranslationAudioInputState.shouldSuppressPlayback(phoneMicrophone: false, bluetoothOutput: true),
              "Glasses mic must not upload glasses playback")
        let bluetoothPlayback = gate.playbackScheduled(duration: 2, suppressesInput: false, now: now)
        check(gate.canSendAudio(opened: true, ready: true, now: now), "Bluetooth playback does not cut phone microphone uploads")
        gate.playbackCompleted(bluetoothPlayback, now: now.addingTimeInterval(2))
        check(gate.canSendAudio(opened: true, ready: true, now: now.addingTimeInterval(2)),
              "Bluetooth playback completion adds no artificial silence")

        var recovery = TranslationCaptureRecoveryState()
        check(recovery.allowRestart(now: 1), "Recover first hardware route failure")
        check(recovery.allowRestart(now: 3), "Recover second hardware route failure")
        check(recovery.allowRestart(now: 5), "Recover third hardware route failure")
        check(!recovery.allowRestart(now: 7), "Persistent capture failure cannot restart indefinitely")
        check(recovery.allowRestart(now: 31), "Healthy later capture has a fresh recovery budget")

        var sends = TranslationSocketSendQueue()
        check(sends.append(Data([1, 2]), kind: .pcm, now: 1), "Queue PCM")
        check(sends.append(Data("stop".utf8), kind: .json("stop"), now: 2), "Stop follows accepted PCM")
        let firstSend = sends.takeNext()!
        check(sends.takeNext() == nil, "Only one send may be in flight")
        check(!sends.complete(firstSend.id + 1), "Wrong completion cannot release next packet")
        check(sends.oldestAge(now: 16) == TranslationSocketSendQueue.sendTimeout, "Stalled first packet reaches send deadline")
        check(sends.complete(firstSend.id), "Complete PCM")
        let stopSend = sends.takeNext()!
        if case .json(let type) = stopSend.kind {
            check(type == "stop", "Drain stop after audio")
        } else { preconditionFailure("Stop packet lost its kind") }
        sends.reset()
        check(!sends.complete(stopSend.id), "Cancelled completion must not affect new queue")
        check(sends.byteCount == 0 && sends.takeNext() == nil, "Reset releases pending buffers")
        check(sends.append(Data(repeating: 0, count: TranslationSocketSendQueue.maxPCMBytes), kind: .pcm, now: 20), "Bounded queue accepts its audio limit")
        check(!sends.append(Data([0, 0]), kind: .pcm, now: 21), "Backlog overflow cannot grow memory or replay stale speech")
        sends.reset()
        check(sends.append(Data([0, 0]), kind: .pcm, now: 22), "New session has no old backlog")
        check(sends.takeNext()!.id != stopSend.id, "Packet IDs survive resets to reject stale completions")

        var waitingAudio = TranslationGlassesPlaybackQueue()
        check(waitingAudio.append(Data([1, 0]), now: 10), "Wait for actual Bluetooth audio")
        check(waitingAudio.append(Data([2, 0]), now: 19), "Preserve ordered speech while waiting")
        check(!waitingAudio.timedOut(now: 19.9), "Allow ten seconds for route readiness")
        check(waitingAudio.timedOut(now: 20), "Additional chunks cannot extend route timeout")
        check(waitingAudio.chunks.first == Data([1, 0]), "Keep first speech chunk first")
        waitingAudio.removeFirst()
        check(waitingAudio.chunks.first == Data([2, 0]), "Route recovery drains in order")
        waitingAudio.reset()
        check(waitingAudio.byteCount == 0 && !waitingAudio.timedOut(now: 100), "Close discards waiting audio and deadline")
        check(!waitingAudio.append(Data(repeating: 0, count: 2_000_001), now: 100), "Route queue bounds audio memory")

        var glasses = TranslationGlassesRecordingState()
        check(!glasses.hasSentCommand, "Opening page does not claim mic")
        check(!glasses.confirmStarted(), "Unsolicited ACK cannot start recording")
        glasses.begin()
        check(glasses.shouldSendStart, "First server ready should send BLE start")
        check(glasses.commandSent(), "BLE start sent exactly once")
        check(glasses.isWaitingForDevice, "Wait for device ACK or valid Gen2 DATA")
        check(!glasses.shouldSendStart, "Repeated ready must not issue another BLE start")
        check(!glasses.commandSent(), "Repeated command request is rejected")
        check(glasses.confirmStarted(), "Valid ACK or decoded DATA confirms recording")
        check(!glasses.isWaitingForDevice, "Valid DATA disarms start timeout")
        check(glasses.acceptsAudio, "Confirmed session accepts audio")
        check(!glasses.confirmStarted(), "Duplicate ACK must not reset decoder")
        glasses.drain()
        check(glasses.acceptsAudio, "Gen1 stop retains tail audio until END or drain timeout")
        check(glasses.hasSentCommand, "Draining keeps device ownership")
        check(!glasses.shouldSendStart, "Ready during drain cannot restart device")
        glasses.reset()
        check(!glasses.acceptsAudio, "END discards tail audio")
        check(!glasses.confirmStarted(), "Late START after stop cannot reopen input")
        glasses.begin()
        glasses.reset()
        check(!glasses.shouldSendStart, "Cancellation before service ready prevents BLE start")
        glasses.begin()
        glasses.commandSent()
        glasses.reset()
        check(!glasses.confirmStarted(), "ACK after startup timeout remains discarded")
        print("TranslationAudioSessionTests: \(assertions) assertions passed")
    }
}
