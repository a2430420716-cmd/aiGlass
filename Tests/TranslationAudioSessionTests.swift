import Foundation

@main
struct TranslationAudioSessionTests {
    static func main() {
        var assertions = 0
        func check(_ condition: @autoclosure () -> Bool, _ message: String) {
            assertions += 1
            precondition(condition(), message)
        }

        var pcm = TranslationPCMStatistics()
        check(pcm.rms == 0 && pcm.durationMs == 0, "Empty PCM has finite diagnostics")
        pcm.append(Data([0, 0, 0, 0x80, 0xFF, 0x7F]))
        check(pcm.samples == 3 && pcm.bytes == 6, "Count PCM16 samples")
        check(pcm.peak == 32_768, "Negative full scale must not overflow Int16")
        check(abs(pcm.rms - sqrt((Double(32_768) * 32_768 + Double(32_767) * 32_767) / 3)) < 0.001,
              "Read signed little-endian audio when computing energy")
        var silence = TranslationPCMStatistics()
        silence.append(Data(repeating: 0, count: 32_000))
        check(silence.durationMs == 1_000 && silence.peak == 0 && silence.rms == 0,
              "One second of silence remains distinguishable from missing audio")

        var attempt = TranslationConnectionAttempt()
        check(!attempt.isCurrent(0), "No callback is current before connect")
        let first = attempt.begin()
        check(attempt.isCurrent(first), "First URL lookup belongs to current connection")
        attempt.cancel()
        check(!attempt.isCurrent(first), "Closing suppresses cancelled socket errors")
        check(!attempt.isCurrent(attempt.current), "Closed session cannot deliver callbacks")
        let second = attempt.begin()
        check(!attempt.isCurrent(first), "Old URL response cannot open a replacement socket")
        check(attempt.isCurrent(second), "New session remains current after stale callback")
        let third = attempt.begin()
        check(!attempt.isCurrent(second), "Reconnect invalidates previous receive loop")
        check(attempt.isCurrent(third), "Latest receive loop is accepted")

        let now = Date(timeIntervalSince1970: 1_000)
        var gate = TranslationAudioInputState()
        gate.serviceReady()
        check(!gate.canSendAudio(opened: true, ready: true), "Ready alone cannot start the mic")
        check(!gate.start(opened: false, ready: true, now: now), "Closed socket rejects start")
        check(!gate.recording, "Failed start must not save recording intent")
        check(!gate.start(opened: true, ready: false, now: now), "Unready socket rejects start")
        check(gate.start(opened: true, ready: true, now: now), "Device START opens input")
        check(gate.canSendAudio(opened: true, ready: true), "PCM can flow after START")
        gate.serviceReady()
        check(gate.canSendAudio(opened: true, ready: true), "Duplicate ready must not mute ongoing recording")
        check(gate.start(opened: true, ready: true, now: now), "Duplicate start is idempotent")
        gate.beginBackendProcessing()
        check(!gate.canSendAudio(opened: true, ready: true), "Backend busy temporarily gates PCM")
        gate.serviceReady()
        check(gate.canSendAudio(opened: true, ready: true), "Ready resumes recording after backend busy")
        gate.beginBackendProcessing()
        gate.backendTurnFinished()
        check(gate.canSendAudio(opened: true, ready: true), "Turn final resumes existing recording")
        gate.stop(now: now)
        check(!gate.canSendAudio(opened: true, ready: true), "Local stop closes input")
        gate.serviceReady()
        gate.backendTurnFinished()
        check(!gate.canSendAudio(opened: true, ready: true), "Late ready/final cannot reopen a stopped mic")
        check(!gate.start(opened: true, ready: true, now: now.addingTimeInterval(0.1)), "Rapid restart remains debounced")
        check(gate.start(opened: true, ready: true, now: now.addingTimeInterval(0.5)), "Intentional later start succeeds")
        check(!gate.canSendAudio(opened: false, ready: true), "Disconnect suppresses PCM")
        check(!gate.canSendAudio(opened: true, ready: false), "Unready socket suppresses PCM")
        gate.close()
        check(!gate.recording, "Close removes old recording intent")
        check(gate.start(opened: true, ready: true, now: now), "New socket has no old stop debounce")

        var glasses = TranslationGlassesRecordingState()
        check(!glasses.hasSentCommand, "Opening page does not claim mic")
        check(!glasses.confirmStarted(), "Unsolicited ACK cannot start recording")
        glasses.begin()
        check(glasses.shouldSendStart, "First server ready should send BLE start")
        check(glasses.commandSent(), "BLE start sent exactly once")
        check(glasses.isWaitingForDevice, "Wait for device ACK or valid Gen2 DATA")
        check(!glasses.shouldSendStart, "Repeated ready must not issue another BLE start")
        check(!glasses.commandSent(), "Repeated command request is rejected")
        check(glasses.confirmStarted(), "Valid ACK or decoded DATA confirms recording")
        check(!glasses.isWaitingForDevice, "Valid DATA disarms start timeout")
        check(glasses.acceptsAudio, "Confirmed session accepts audio")
        check(!glasses.confirmStarted(), "Duplicate ACK must not reset decoder")
        glasses.drain()
        check(glasses.acceptsAudio, "Gen1 stop retains tail audio until END or drain timeout")
        check(glasses.hasSentCommand, "Draining keeps device ownership")
        check(!glasses.shouldSendStart, "Ready during drain cannot restart device")
        glasses.reset()
        check(!glasses.acceptsAudio, "END discards tail audio")
        check(!glasses.confirmStarted(), "Late START after stop cannot reopen input")
        glasses.begin()
        glasses.reset()
        check(!glasses.shouldSendStart, "Cancellation before service ready prevents BLE start")
        glasses.begin()
        glasses.commandSent()
        glasses.reset()
        check(!glasses.confirmStarted(), "ACK after startup timeout remains discarded")
        print("TranslationAudioSessionTests: \(assertions) assertions passed")
    }
}
